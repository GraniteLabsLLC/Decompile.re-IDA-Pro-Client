"""Symbol provenance for reversal training samples."""

import idc
import ida_lines
import ida_nalt

try:
    import ida_netnode
except ImportError:
    ida_netnode = None

from .navigation import is_autogenerated_name


_PROVENANCE_NODE = "$ decompile.re symbol provenance"
_PDB_NODE = "$ pdb"


def _node(name: str, create: bool = False):
    node = ida_netnode.netnode(name, 0, create)
    return node if node.index() != ida_netnode.BADNODE else None


def _pdb_import_state() -> tuple[bool | None, str]:
    if ida_netnode is None:
        return None, "unavailable"
    try:
        provenance = _node(_PROVENANCE_NODE)
        if provenance is not None and provenance.altval(0) == 1:
            return True, "previous_successful_import"
        pdb = _node(_PDB_NODE)
        if pdb is None:
            return False, "no_import_record"
        # The PDB plugin stores its boolean load result at altval(0).
        # Zero can also follow a partial/failed import; an image base can be
        # stored here before loading. Neither proves a clean database.
        if pdb.altval(0) != 1:
            return None, "inconclusive_import_record"
        try:
            _node(_PROVENANCE_NODE, create=True).altset(0, 1)
        except Exception:
            pass
        return True, "successful_import"
    except Exception:
        return None, "unavailable"


def record_engine_function_name(ea: int) -> None:
    """Remember successful plugin renames in the IDB, across sessions."""
    if ida_netnode is None:
        return
    try:
        name = idc.get_func_name(ea) or ""
        if name:
            _node(_PROVENANCE_NODE, create=True).hashset(f"{ea:x}", name)
    except Exception:
        pass


def _function_name_source(ea: int) -> str:
    try:
        name = idc.get_func_name(ea) or ""
    except Exception:
        return "unknown"
    if ida_netnode is not None:
        try:
            node = _node(_PROVENANCE_NODE)
            if node is not None and name and node.hashstr(f"{ea:x}") == name:
                return "engine"
        except Exception:
            pass
    if name and is_autogenerated_name(name):
        return "auto"
    # IDA's user-name flag cannot distinguish PDB, manual, export, and other
    # imported names. A loaded PDB alone does not establish this name's source.
    return "unknown"


def get_symbol_provenance(ea: int) -> dict:
    pdb_loaded, pdb_detection = _pdb_import_state()
    try:
        source_mapping = bool(ida_lines.get_sourcefile(ea))
    except Exception:
        source_mapping = None
    result = {
        "schema_version": 1,
        "pdb_loaded": pdb_loaded,
        "pdb_detection": pdb_detection,
        "function_name_source": _function_name_source(ea),
        "source_mapping_present": source_mapping,
    }
    try:
        digest = ida_nalt.retrieve_input_file_sha256()
        if isinstance(digest, bytes) and len(digest) == 32:
            result["binary_sha256"] = digest.hex()
    except Exception:
        pass
    return result
